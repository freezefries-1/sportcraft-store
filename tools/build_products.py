#!/usr/bin/env python3
"""Turn a Shopify product export (CSV) into data/products.js for the site.

Usage:  python3 tools/build_products.py [path/to/products.csv]
"""
import csv
import json
import re
import sys
from collections import OrderedDict
from html import escape
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import quote, urlsplit

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "products.csv"
OUT = ROOT / "data" / "products.js"

ALLOWED = {"p", "br", "strong", "b", "em", "i", "ul", "ol", "li", "h2", "h3", "h4"}
SKIP_CONTENT = {"script", "style", "iframe"}


class Cleaner(HTMLParser):
    """Keep a small set of formatting tags, drop every attribute and other tag."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []
        self.skip = 0

    def handle_starttag(self, tag, attrs):
        if tag in SKIP_CONTENT:
            self.skip += 1
        elif tag in ALLOWED and not self.skip:
            self.out.append(f"<{tag}>")

    def handle_endtag(self, tag):
        if tag in SKIP_CONTENT:
            self.skip = max(0, self.skip - 1)
        elif tag in ALLOWED and tag != "br" and not self.skip:
            self.out.append(f"</{tag}>")

    def handle_data(self, data):
        if not self.skip:
            self.out.append(escape(data, quote=False))


def clean_html(html):
    c = Cleaner()
    c.feed(html or "")
    c.close()
    text = "".join(c.out)
    text = re.sub(r"<p>(\s|&nbsp;|<br>)*</p>", "", text)
    return text.strip()


def pretty(value):
    """'rose-gold' -> 'Rose Gold', 'blue-white-1' -> 'Blue White'; leave '1.25mm', 'Reel (200m)' alone."""
    v = value.strip()
    if not re.fullmatch(r"[a-z0-9-]+", v) or re.fullmatch(r"[\d.]+mm", v):
        return v
    v = re.sub(r"-\d+$", "", v)
    return " ".join(w[:1].upper() + w[1:] if w[:1].isalpha() else w for w in v.split("-"))


def local(url):
    """Use the copy saved by tools/download_images.py when there is one."""
    url = (url or "").strip()
    name = Path(urlsplit(url).path).name
    if name and (ROOT / "images" / name).exists():
        return "images/" + quote(name)
    return url


def main():
    with open(SRC, newline="", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))

    groups = OrderedDict()
    for r in rows:
        groups.setdefault(r["Handle"], []).append(r)

    products = []
    for handle, rs in groups.items():
        head = rs[0]
        if head.get("Status", "active") != "active":
            continue
        names = [head.get(f"Option{i} Name", "").strip() for i in (1, 2, 3)]
        names = [n for n in names if n]
        if names == ["Title"]:
            names = []
        variants = []
        for r in rs:
            if r["Variant Price"] == "":
                continue
            variants.append({
                "o": [pretty(r[f"Option{i + 1} Value"]) for i in range(len(names))],
                "price": float(r["Variant Price"]),
                "img": local(r.get("Variant Image", "")),
            })
        images = []
        for r in sorted((r for r in rs if r["Image Src"]), key=lambda r: int(r["Image Position"] or 0)):
            if local(r["Image Src"]) not in images:
                images.append(local(r["Image Src"]))
        title = head["Title"].strip()
        preloved = bool(re.match(r"\[pre-loved\]", title, re.I))
        products.append({
            "handle": handle,
            "title": re.sub(r"^\[pre-loved\]\s*", "", title, flags=re.I),
            "vendor": head["Vendor"].strip(),
            "type": head["Type"].strip() or "Other",
            "preloved": preloved,
            "options": names,
            "variants": variants,
            "images": images,
            "html": clean_html(head["Body (HTML)"]),
        })

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_products.py — edit the CSV and re-run rather than editing by hand.\n"
        "window.PRODUCTS = " + json.dumps(products, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(products)} products to {OUT}")


if __name__ == "__main__":
    main()
